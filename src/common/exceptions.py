"""
Базовые доменные исключения, общие для Inference и Train.

Отдельный базовый класс AppError нужен, чтобы наверху (например, в FastAPI
exception handler'е инференса) можно было одним обработчиком поймать "все
наши ожидаемые доменные ошибки" и не путать их с непредвиденными багами —
для обычного Exception нужна другая реакция (500 + полный traceback в лог),
а для AppError — аккуратный, понятный клиенту 4xx с текстом причины.
"""


class AppError(Exception):
    """Базовое исключение для всех ожидаемых доменных ошибок проекта."""


class EmptyTextError(AppError):
    """headline/short_description оказались пустыми после нормализации текста."""
